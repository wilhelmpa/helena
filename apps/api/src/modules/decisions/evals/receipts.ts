// Labelled cases of receipt matching (docs/helena-decisions/decisions.md §6): a receipt (a bill
// we pay or an invoice we wrote), the bank transactions the matcher found as candidates, and
// the one that pays it, or none. Amounts and purposes follow German bank statements (SEPA
// `EREF+`/`SVWZ+`/`MREF+`, card payments, PayPal). Issuers, people and numbers are invented;
